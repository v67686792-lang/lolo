/* случайный отрезок нужного типа (целые мм, I октант) */
NG.randSeg = function(type, rnd){
  rnd = rnd || Math.random;
  const R=(a,b)=>Math.round(a+rnd()*(b-a));
  const far=(v,lo,hi,min)=>{ let w, i=0; do { w=R(lo,hi); i++; } while (Math.abs(w-v)<min && i<50); return w; };
  let A={x:R(55,85), y:R(8,45), z:R(8,45)}, B;
  const x2=R(12,40);
  switch(type){
    case 'ga': case 'gd': {
      let y2, z2, i=0;
      do { y2=far(A.y,5,50,12); z2=far(A.z,5,50,12); i++; }
      while ((((A.y-y2)*(A.z-z2)<0)?'ga':'gd')!==type && i<60);
      B={x:x2,y:y2,z:z2}; break;
    }
    case 'h': B={x:x2,y:far(A.y,5,50,12),z:A.z}; break;
    case 'f': B={x:x2,y:A.y,z:far(A.z,5,50,12)}; break;
    case 'p': B={x:A.x,y:far(A.y,5,50,12),z:far(A.z,5,50,12)}; break;
    case 'hp': B={x:A.x,y:A.y,z:far(A.z,5,50,15)}; break;
    case 'fp': B={x:A.x,y:far(A.y,5,50,15),z:A.z}; break;
    case 'pp': B={x:x2,y:A.y,z:A.z}; break;
  }
  if (type==='ga'||type==='gd'){ if (NG.classify(A,B)!==type){ const t=B.z; B.z=A.z; A.z=t; } }
  return {A,B};
};
